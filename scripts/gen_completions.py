#!/usr/bin/env python3
"""Generate c_src/commands/completions.c from the command dispatch table.

The one source of truth for which subcommands exist is the dispatch chain
in bcachefs_main() - the static list this file used to carry by hand
drifted from it. This script reads the dispatch table, validates the
handlers it names, and prints a complete completions.c.

Usage: gen_completions.py <bcachefs.c> [<cmds.h>] > completions.c

The output is deterministic: identical inputs produce identical bytes, so
the Makefile rule can rebuild only on real changes (cmp -s || mv).
"""

import re
import sys

PROLOG = """\
/*
 * GENERATED by scripts/gen_completions.py from the command dispatch table
 * in c_src/bcachefs.c - do not edit; changes belong in the dispatch table
 * or the generator. Regenerate with:
 *
 *   python3 scripts/gen_completions.py c_src/bcachefs.c \\
 *       > c_src/commands/completions.c
 */

#include <stdio.h>
#include <string.h>

#include "tools-util.h"
#include "cmds.h"

static const char *subcommands[] = {
"""

EPILOG = """\tNULL
};

static const char *global_opts[] = {
\t"-h", "--help",
\t"-v", "--verbose",
\tNULL
};

static void print_bash_completion(void)
{
\tprintf("_bcachefs()\\n"
\t       "{\\n"
\t       "    local cur prev opts\\n"
\t       "    COMPREPLY=()\\n"
\t       "    cur=\\"${COMP_WORDS[COMP_CWORD]}\\"\\n"
\t       "    prev=\\"${COMP_WORDS[COMP_CWORD-1]}\\"\\n"
\t       "    opts=\\"");
\tfor (int i = 0; subcommands[i]; i++)
\t\tprintf("%s ", subcommands[i]);
\tprintf("\\"\\n"
\t       "    global_opts=\\"");
\tfor (int i = 0; global_opts[i]; i++)
\t\tprintf("%s ", global_opts[i]);
\tprintf("\\"\\n\\n"
\t       "    if [[ ${COMP_CWORD} -eq 1 ]] ; then\\n"
\t       "        COMPREPLY=( $(compgen -W \\"${opts} ${global_opts}\\" -- ${cur}) )\\n"
\t       "        return 0\\n"
\t       "    fi\\n"
\t       "\\n"
\t       "    # Subcommand-specific completion could be added here\\n"
\t       "}\\n"
\t       "complete -F _bcachefs bcachefs\\n");
}

static void print_zsh_completion(void)
{
\tprintf("#compdef bcachefs\\n"
\t       "\\n"
\t       "_bcachefs() {\\n"
\t       "    local -a commands\\n"
\t       "    commands=(\\n");
\tfor (int i = 0; subcommands[i]; i++)
\t\tprintf("        '%s'\\n", subcommands[i]);
\tprintf("    )\\n"
\t       "    _describe -t commands 'bcachefs commands' commands\\n"
\t       "}\\n"
\t       "\\n"
\t       "_bcachefs\\n");
}

static void print_fish_completion(void)
{
\tprintf("# bcachefs fish completion\\n"
\t       "\\n");
\tfor (int i = 0; subcommands[i]; i++)
\t\tprintf("complete -c bcachefs -n \\"not __fish_seen_subcommand\\" -a \\"%s\\"\\n", subcommands[i]);
\tprintf("\\n"
\t       "complete -c bcachefs -n \\"__fish_seen_subcommand\\" -a \\"-h --help -v --verbose\\"\\n");
}

int cmd_completions(int argc, char *argv[])
{
\tif (argc < 2) {
\t\tputs("Usage: bcachefs completions <shell>");
\t\treturn -EINVAL;
\t}

\tif (!strcmp(argv[1], "bash")) {
\t\tprint_bash_completion();
\t} else if (!strcmp(argv[1], "zsh")) {
\t\tprint_zsh_completion();
\t} else if (!strcmp(argv[1], "fish")) {
\t\tprint_fish_completion();
\t} else {
\t\tdie("shell %s not supported yet", argv[1]);
\t}
\treturn 0;
}
"""


def parse_dispatch(src):
    """Pull (names, handler, condition) out of bcachefs_main()'s dispatch.

    A group starts at `if (!strcmp(cmd_name, "a"))`, continues through
    `|| !strcmp(cmd_name, "b")` lines, and closes at its `return cmd_x(...)`.
    Preprocessor conditionals wrapping a group (the BCACHEFS_FUSE gate on
    fusemount) are carried through so the generated file stays compilable
    with and without them.
    """
    start = src.find("int bcachefs_main(")
    if start < 0:
        sys.exit(f"error: {sys.argv[1]}: bcachefs_main() not found - "
                 "the dispatch table moved out of bcachefs.c?")
    try:
        end = src.index('printf("Unknown command', start)
    except ValueError:
        sys.exit(f"error: {sys.argv[1]}: dispatch tail (Unknown command "
                 "printf) not found - bcachefs_main() layout changed")
    body = src[start:end]

    strcmp_re = re.compile(r'!strcmp\(cmd_name, "([^"]+)"\)')
    if_re = re.compile(r'if \(\s*!strcmp\(cmd_name, "([^"]+)"\)')
    ret_re = re.compile(r'return (cmd_\w+)\(')

    commands = []
    names = None		# group being accumulated, None between groups
    cond = None
    cond_stack = []		# preprocessor conditionals

    for raw in body.split("\n"):
        line = raw.strip()

        # preprocessor tracking - fusemount is gated on BCACHEFS_FUSE
        if line.startswith("#"):
            m = re.match(r'#\s*(ifdef|ifndef|if|else|elif|endif)\b\s*(.*)', line)
            if m:
                d, expr = m.groups()
                if d in ("ifdef", "ifndef", "if"):
                    cond_stack.append((d, expr))
                elif d == "endif":
                    if cond_stack:
                        cond_stack.pop()
                cond = " && ".join(e for _, e in cond_stack) or None
            continue

        m = if_re.search(line)
        if m and names is None:
            # a group may carry more names on the if line itself
            # (subvolume || subvol)
            names = [n for n in strcmp_re.findall(line)]
            cond = " && ".join(e for _, e in cond_stack) or None
            continue

        if names is not None:
            for n in strcmp_re.findall(line):
                names.append(n)

            m = ret_re.search(line)
            if m:
                commands.append((tuple(names), m.group(1), cond))
                names = None
            elif "return" in line:
                # a group closing on a plain `return 0` - the help group -
                # is not a subcommand
                names = None

    return commands


def validate(commands, cmds_h, bcachefs_c):
    """Every handler must be declared in cmds.h or defined in bcachefs.c
    (cmd_version is a static inline in the latter)."""
    declared = set(re.findall(r'\bint\s+(cmd_\w+)\s*\(', cmds_h))
    defined = set(re.findall(r'\b(?:static\s+)?(?:inline\s+)?int\s+(cmd_\w+)\s*\(',
                             bcachefs_c))

    seen = set()
    problems = []
    for names, handler, _ in commands:
        if handler not in declared and handler not in defined:
            problems.append(f"{handler} (from {'/'.join(names)}): "
                            "not declared in cmds.h nor defined in bcachefs.c")
        for n in names:
            if n in seen:
                problems.append(f"duplicate command name {n!r}")
            seen.add(n)

    if not commands:
        problems.append("no commands parsed from the dispatch table - "
                        "the parser and bcachefs_main() have diverged")
    return problems


def emit(commands):
    out = [PROLOG]
    for names, _, cond in commands:
        if cond:
            out.append(f"#ifdef {cond}\n")
        for n in names:
            out.append(f'\t"{n}",\n')
        if cond:
            out.append("#endif\n")
    out.append(EPILOG)
    return "".join(out)


def main():
    if len(sys.argv) < 2:
        sys.exit(f"usage: {sys.argv[0]} <bcachefs.c> [<cmds.h>]")

    bcachefs_c = open(sys.argv[1]).read()
    cmds_h = open(sys.argv[2]).read() if len(sys.argv) > 2 else ""

    commands = parse_dispatch(bcachefs_c)
    problems = validate(commands, cmds_h, bcachefs_c)
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        sys.exit(1)

    sys.stdout.write(emit(commands))


if __name__ == "__main__":
    main()
