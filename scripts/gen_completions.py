#!/usr/bin/env python3
"""Generate c_src/commands/completions.c from the command sources.

Sources of truth, in order of specificity:

  1. the dispatch chains - bcachefs_main() in c_src/bcachefs.c for the
     top-level commands, and the pop_cmd()/strcmp() chains inside group
     commands (device, fs, subvolume, reconcile) for the second level;
  2. each command's option definitions - either its own
     `static const struct option longopts[]` + getopt_long() optstring,
     or a flag filter into the fs option table (bch2_cmdline_opts_get /
     bch2_cmdline_opt_parse / an `opt_flags = OPT_...` local), whose
     names and help strings come from the BCH_OPTS() x-macro in
     fs/opts.h;
  3. the per-command usage() functions, whose text carries the option
     descriptions (and the one-line command description after the
     leading "bcachefs ... - ").

The script prints a complete completions.c: three fully rendered shell
scripts (bash/zsh/fish) as string literals plus a cmd_completions() that
picks one. Commands gated on BCACHEFS_FUSE (fusemount) render as
separate C string fragments wrapped in #ifdef, so the data matches the
build. Output is deterministic, so the Makefile rule can rebuild on
content change only (cmp -s || mv).

Usage: gen_completions.py <bcachefs.c> <cmds.h> <fs/opts.h> \
           <commands dir> > completions.c
"""

import glob
import os
import re
import sys

FUSE_MARK = "#!BCACHEFS_FUSE!"      # shell-line prefix: gated fragment

PROLOG = """\
/*
 * GENERATED by scripts/gen_completions.py - do not edit; changes belong
 * in the command sources or the generator. Regenerate with:
 *
 *   make c_src/commands/completions.c
 */

#include <stdio.h>
#include <string.h>

#include "tools-util.h"
#include "cmds.h"
"""

EPILOG = """
int cmd_completions(int argc, char *argv[])
{
\tif (argc < 2) {
\t\tputs("Usage: bcachefs completions <shell>");
\t\treturn -EINVAL;
\t}

\tif (!strcmp(argv[1], "bash")) {
\t\tfputs(COMPLETIONS_BASH, stdout);
\t} else if (!strcmp(argv[1], "zsh")) {
\t\tfputs(COMPLETIONS_ZSH, stdout);
\t} else if (!strcmp(argv[1], "fish")) {
\t\tfputs(COMPLETIONS_FISH, stdout);
\t} else {
\t\tdie("shell %s not supported yet", argv[1]);
\t}
\treturn 0;
}
"""


# ---------------------------------------------------------------- C scanning

def strip_c(text):
    """Blank out comments and string/char literal contents, preserving
    newlines and string boundaries - for brace matching and idents."""
    out = list(text)
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c == '/' and i + 1 < n and text[i + 1] == '*':
            j = text.find('*/', i + 2)
            j = n if j < 0 else j + 2
            for k in range(i, j):
                if out[k] != '\n':
                    out[k] = ' '
            i = j
        elif c == '/' and i + 1 < n and text[i + 1] == '/':
            j = text.find('\n', i)
            j = n if j < 0 else j
            for k in range(i, j):
                out[k] = ' '
            i = j
        elif c in ('"', "'"):
            q = c
            j = i + 1
            while j < n:
                if text[j] == '\\':
                    j += 2
                    continue
                if text[j] == q:
                    j += 1
                    break
                j += 1
            for k in range(i + 1, min(j, n) - 1):
                out[k] = ' '
            i = j
        else:
            i += 1
    return "".join(out)


def c_strings(text):
    """Concatenated string literals of a (usage) function body, with the
    C escapes that matter decoded."""
    body = []
    i, n = 0, len(text)
    while i < n:
        if text[i] == '"':
            j = i + 1
            buf = []
            while j < n and text[j] != '"':
                if text[j] == '\\':
                    esc = text[j + 1] if j + 1 < n else ''
                    buf.append({'n': '\n', 't': '\t', '\\': '\\',
                                '"': '"'}.get(esc, esc))
                    j += 2
                    continue
                buf.append(text[j])
                j += 1
            body.append("".join(buf))
            i = j + 1
        else:
            i += 1
    return "".join(body)


def brace_span(text, start):
    """Index just past the '}' matching the first '{' at/after @start."""
    stripped = strip_c(text)
    i = stripped.find('{', start)
    if i < 0:
        return start
    depth = 0
    while i < len(stripped):
        if stripped[i] == '{':
            depth += 1
        elif stripped[i] == '}':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return len(stripped)


# ------------------------------------------------------- dispatch chains

def parse_dispatch(body, if_re, strcmp_re, ret_re, warnings, where):
    """Walk a dispatch chain: groups of strcmp() names closed by a
    `return cmd_h()` (a plain return closes the group as non-command)."""
    commands = []
    names = None
    cond_stack = []
    cond = None

    for raw in body.split("\n"):
        line = raw.strip()

        if line.startswith("#"):
            m = re.match(r'#\s*(ifdef|ifndef|if|else|elif|endif)\b\s*(.*)', line)
            if m:
                d, expr = m.groups()
                if d in ("ifdef", "ifndef", "if"):
                    cond_stack.append(expr)
                elif d == "endif":
                    if cond_stack:
                        cond_stack.pop()
                cond = " && ".join(cond_stack) or None
            continue

        m = if_re.search(line)
        if m and names is None:
            names = strcmp_re.findall(line)
            cond = " && ".join(cond_stack) or None
            continue

        if names is not None:
            names.extend(strcmp_re.findall(line))
            m = ret_re.search(line)
            if m:
                commands.append((tuple(names), m.group(1), cond))
                names = None
            elif "return" in line:
                names = None

    if names is not None:
        warnings.append(f"{where}: dispatch group {'/'.join(names)} "
                        "never closed - dropped")
    return commands


def parse_top_dispatch(bcachefs_c, warnings):
    start = bcachefs_c.find("int bcachefs_main(")
    if start < 0:
        sys.exit("error: bcachefs_main() not found in bcachefs.c")
    try:
        end = bcachefs_c.index('printf("Unknown command', start)
    except ValueError:
        sys.exit("error: dispatch tail not found in bcachefs.c")
    return parse_dispatch(bcachefs_c[start:end],
                          re.compile(r'if \(\s*!strcmp\(cmd_name, "([^"]+)"\)'),
                          re.compile(r'!strcmp\(cmd_name, "([^"]+)"\)'),
                          re.compile(r'return (cmd_\w+)\('),
                          warnings, "bcachefs.c")


def parse_group_dispatch(func_text, handler, warnings):
    return parse_dispatch(func_text,
                          re.compile(r'if \(\s*!strcmp\(cmd, "([^"]+)"\)'),
                          re.compile(r'!strcmp\(cmd, "([^"]+)"\)'),
                          re.compile(r'return (cmd_\w+)\('),
                          warnings, handler)


# ------------------------------------------------------- options

# the arg-kind field is written either as the enum or as its number
LONGOPT_ENTRY = re.compile(
    r'\{\s*"([^"]+)"\s*,\s*([^,]+?)\s*,\s*[^,]+,\s*(?:\'(.)\'|([0-9]+|\w+))\s*\}')
OPTSTRING = re.compile(r'getopt_long(?:_only)?\s*\([^,]*,[^,]*,\s*"([^"]*)"')
USAGE_CALL = re.compile(r'\b(\w*usage)\s*\(')


def parse_longopts(func_text):
    """[(long name, short letter|None, takes value)] from the longopts
    table and optstring in this function - short letters cross-checked
    against the optstring (enum-valued entries have none)."""
    m = OPTSTRING.search(func_text)
    optstring = m.group(1) if m else ""
    shorts = set()
    for i, c in enumerate(optstring):
        if c != ':':
            shorts.add(c)

    takes_kinds = {'required_argument', 'optional_argument', '1', '2'}
    opts = []
    seen = set()
    for m in LONGOPT_ENTRY.finditer(func_text):
        name, arg, ch, num = m.groups()
        if name in seen:
            continue
        seen.add(name)
        short = ch if ch and ch in shorts else None
        opts.append((name, short, arg in takes_kinds))
    return opts


def parse_opts_h(opts_h_text):
    """(name, flags set, help) for every entry of the BCH_OPTS x-macro."""
    m = re.search(r'#define\s+BCH_OPTS\(\)(.*?)(?=#define\s|\Z)',
                  opts_h_text, re.S)
    block = m.group(1) if m else opts_h_text
    entries = []
    for chunk in re.split(r'\n\s*x\(', block)[1:]:
        name = re.match(r'\s*(\w+)', chunk)
        if not name:
            continue
        flags = set(re.findall(r'\bOPT_[A-Z]+\b', chunk))
        strings = re.findall(r'"((?:[^"\\]|\\.)*)"', chunk)
        help_text = strings[-1].strip() if strings else ""
        entries.append((name.group(1), flags, help_text))
    return entries


def parse_usage(usage_fn_text):
    """(command description, {long name: help}) from a usage() body."""
    text = c_strings(usage_fn_text)
    desc = ""
    m = re.match(r'\s*bcachefs\s+\S+\s+-\s+(.*)', text)
    if m:
        desc = m.group(1).strip()

    helps = {}
    cur = None
    in_options = False
    for line in text.split("\n"):
        if re.match(r'\s*Options:', line):
            in_options = True
            continue
        if re.match(r'\s*Report bugs', line):
            break
        if not in_options:
            continue
        m = re.match(r'\s+(?:-(\w),\s+)?--([\w-]+)\S*\s\s+(\S.*)', line)
        if m:
            cur = m.group(2)
            helps[cur] = m.group(3).strip()
            continue
        if cur and line.strip():
            helps[cur] = (helps.get(cur, "") + " " + line.strip()).strip()
    return desc, helps


# ------------------------------------------------------- tree building

class Cmd:
    def __init__(self, name, path, handler, gated=None):
        self.name = name
        self.path = path            # tuple, e.g. ("device", "add")
        self.handler = handler
        self.gated = gated          # preprocessor condition or None
        self.children = []
        self.options = []           # (long, short, takes, help)
        self.desc = ""


def walk(cmd):
    yield cmd
    for c in cmd.children:
        yield from walk(c)


def function_span(files, fname):
    """(function text, file text) for a top-level int fn( in the command
    files, or (None, None)."""
    for text in files.values():
        m = re.search(r'^\s*(?:static\s+)?int\s+%s\s*\(' % re.escape(fname),
                      text, re.M)
        if m:
            end = brace_span(text, m.start())
            return text[m.start():end], text
    return None, None


def usage_text_for(files, span):
    m = USAGE_CALL.search(span)
    if not m:
        return None
    return function_span(files, m.group(1))[0]


def collect_options(handler, span, files, opts_table, helps, warnings):
    """[(long, short, takes, help)] from whichever source this function
    uses: the fs option table (via a flag filter) or its own longopts.
    @helps is the usage() help map, reused for descriptions."""
    filt = None
    m = re.search(r'bch2_cmdline_(?:opts_get|opt_parse)\s*\([^;]*?'
                  r'(OPT_[A-Z][A-Z_| ]*)\)', span)
    if m:
        filt = m.group(1)
    else:
        m = re.search(r'\bopt_flags\s*=\s*(OPT_[A-Z][A-Z_| ]*)\s*;', span)
        if m:
            filt = m.group(1)

    if filt:
        want = set(re.findall(r'OPT_[A-Z]+', filt))
        opts = [(name, None, True, help_text)
                for name, flags, help_text in opts_table
                if flags & want]
        if opts:
            return opts, "fs-opts"

    long_opts = parse_longopts(span)
    if long_opts:
        return [(name, short, takes, helps.get(name, ""))
                for name, short, takes in long_opts], "longopts"

    # genuinely option-less commands (groups, positional-only) are not a
    # problem; a usage text advertising options we cannot extract is
    if helps:
        warnings.append(f"{handler}: usage lists options but no option "
                        "source was found")
    return [], "none"


def build_tree(bcachefs_c, func_index, files, opts_table, warnings):
    root = Cmd("bcachefs", (), None)
    root.desc = "bcachefs filesystem tools"
    processed = set()

    def expand(cmd):
        if cmd.handler in processed:
            return
        processed.add(cmd.handler)

        # cmd_version is a static inline in bcachefs.c; cmd_completions
        # lives in the file this generator writes
        if cmd.handler in ("cmd_version", "cmd_completions"):
            return

        span, _ = function_span(files, cmd.handler)
        if not span:
            warnings.append(f"{cmd.handler}: definition not found")
            return

        for names, h, _ in parse_group_dispatch(span, cmd.handler, warnings):
            for n in names:
                child = Cmd(n, cmd.path + (n,), h, cmd.gated)
                cmd.children.append(child)
                expand(child)

        helps = {}
        utext = usage_text_for(files, span)
        if utext:
            cmd.desc, helps = parse_usage(utext)

        cmd.options, _src = collect_options(cmd.handler, span, files,
                                            opts_table, helps, warnings)

    for names, handler, cond in parse_top_dispatch(bcachefs_c, warnings):
        for n in names:
            child = Cmd(n, (n,), handler, cond)
            root.children.append(child)

    for cmd in list(walk(root)):
        if cmd.handler:
            expand(cmd)

    return root


# ------------------------------------------------------- renderers

def sh_quote(s):
    return "'" + s.replace("'", "'\\''") + "'"


def bash_opts(cmd, global_opts=()):
    parts = []
    seen = set()
    for name, short, takes, _ in cmd.options:
        parts.append("--" + name)
        seen.add("--" + name)
        if short:
            parts.append("-" + short)
    for o in global_opts:
        if o not in seen:
            parts.append(o)
    return parts


def render_bash(root):
    """Data tables keyed by the space-joined command path, and a walker
    that picks the deepest matching path."""
    # every key starts with the program name: bash rejects the empty
    # string as an associative-array subscript
    lines = ["# bash completion for bcachefs - generated, do not edit\n",
             "declare -A __bcachefs_known __bcachefs_children "
             "__bcachefs_opts\n\n"]

    for c in walk(root):
        key = " ".join(("bcachefs",) + c.path)
        kids = " ".join(x.name for x in c.children)
        opts = bash_opts(c, () if c.children else ("-h", "--help"))
        mark = FUSE_MARK if c.gated else ""
        known = "" if not c.path else "1"
        out = (f"__bcachefs_known[{sh_quote(key)}]={sh_quote(known)}\n"
               f"__bcachefs_children[{sh_quote(key)}]={sh_quote(kids)}\n"
               f"__bcachefs_opts[{sh_quote(key)}]={sh_quote(' '.join(opts))}\n")
        if mark:
            for l in out.splitlines(True):
                lines.append(FUSE_MARK + l)
        else:
            lines.append(out)

    lines.append("""
_bcachefs() {
    local cur
    cur="${COMP_WORDS[COMP_CWORD]}"

    # deepest command path matched so far
    local i w path="bcachefs" cand
    for ((i = 1; i < COMP_CWORD; i++)); do
        w="${COMP_WORDS[i]}"
        [[ "$w" == -* ]] && break
        cand="$path $w"
        [[ -n "${__bcachefs_known[$cand]:-}" ]] && path="$cand"
    done

    local kids="${__bcachefs_children[$path]:-}"
    local opts="${__bcachefs_opts[$path]:-} -h --help"

    if [[ "$cur" == -* ]]; then
        COMPREPLY=( $(compgen -W "$opts" -- "$cur") )
    elif [[ -n "$kids" ]]; then
        COMPREPLY=( $(compgen -W "$kids" -- "$cur") )
    fi
    # else: a leaf command's positional argument - empty COMPREPLY falls
    # back to readline's default (file) completion
}
complete -F _bcachefs bcachefs
""")
    return "".join(lines)


def render_zsh(root):
    """Same data-table shape as bash, with zsh syntax; subcommand and
    option descriptions via _describe's name:display entries."""
    lines = ["#compdef bcachefs\n",
             "# zsh completion for bcachefs - generated, do not edit\n\n",
             "typeset -A __bcachefs_known __bcachefs_kids __bcachefs_opts\n"
             "typeset -A __bcachefs_kids_d __bcachefs_opts_d\n\n"]

    for c in walk(root):
        key = " ".join(("bcachefs",) + c.path)
        kids = " ".join(x.name for x in c.children)
        kids_d = " ".join(f"{x.name}:{x.desc}" for x in c.children
                          if x.desc)
        opts = []
        opts_d = []
        for name, short, takes, help_text in c.options:
            opts.append("--" + name)
            opts_d.append(f"--{name}:{help_text}" if help_text
                          else f"--{name}")
        if not c.path:
            if "--help" not in opts:
                opts += ["-h", "--help"]
                opts_d += ["-h:Display help"]
        mark = FUSE_MARK if c.gated else ""
        known = "" if not c.path else "1"
        out = (f"__bcachefs_known[{sh_quote(key)}]={sh_quote(known)}\n"
               f"__bcachefs_kids[{sh_quote(key)}]={sh_quote(kids)}\n"
               f"__bcachefs_kids_d[{sh_quote(key)}]={sh_quote(kids_d)}\n"
               f"__bcachefs_opts[{sh_quote(key)}]={sh_quote(' '.join(opts))}\n"
               f"__bcachefs_opts_d[{sh_quote(key)}]={sh_quote(' '.join(opts_d))}\n")
        if mark:
            for l in out.splitlines(True):
                lines.append(FUSE_MARK + l)
        else:
            lines.append(out)

    lines.append("""
_bcachefs() {
    local -a args known next
    local a k matched
    args=( ${words[@]:2} )
    known=( 'bcachefs' )

    for a in $args; do
        [[ "$a" == -* ]] && break
        next=( )
        matched=0
        for k in $known; do
            local cand="$k $a"
            [[ -n "${__bcachefs_known[$cand]:-}" ]] && next+=( "$cand" ) && matched=1
        done
        (( matched )) || break
        known=( $next )
    done

    local k="${known[-1]:-}"
    local -a kids=( ${=${__bcachefs_kids[$k]:-}} )
    local -a kids_d=( ${=${__bcachefs_kids_d[$k]:-}} )
    local -a opts=( ${=${__bcachefs_opts[$k]:-}} )
    local -a opts_d=( ${=${__bcachefs_opts_d[$k]:-}} )

    if (( ${#kids_d} )); then
        _describe -t bcachefs-commands 'subcommand' kids_d
    elif (( ${#kids} )); then
        _describe -t bcachefs-commands 'subcommand' kids
    fi
    if (( ${#opts_d} )); then
        _describe -t bcachefs-options 'option' opts_d
    elif (( ${#opts} )); then
        _describe -t bcachefs-options 'option' opts
    fi
}

_bcachefs "$@"
""")
    return "".join(lines)


def render_fish(root):
    """Flat rules: one per (sub)command and one per option, each with the
    seen_subcommand conditions of its path."""
    lines = ["# fish completion for bcachefs - generated, do not edit\n\n"]

    for c in walk(root):
        if not c.path:
            continue
        # one __fish_seen_subcommand_from call per level, joined with
        # `; and ` - a space-joined form would pass the next function
        # name as an argument of the first
        cond = "; and ".join(f"__fish_seen_subcommand_from {p}"
                             for p in c.path)
        mark = FUSE_MARK if c.gated else ""
        rule = (f"complete -c bcachefs -f -n {sh_quote(cond)} "
                f"-a {sh_quote(c.name)}"
                + (f" -d {sh_quote(c.desc)}" if c.desc else "") + "\n")
        lines.append((FUSE_MARK + rule) if mark else rule)

        for name, short, takes, help_text in c.options:
            rule = "complete -c bcachefs"
            if mark:
                rule = FUSE_MARK + rule
            rule += f" -n {sh_quote(cond)} -l {name}"
            if short:
                rule += f" -s {short}"
            if help_text:
                rule += f" -d {sh_quote(help_text)}"
            lines.append(rule + "\n")

    lines.append("complete -c bcachefs -l help -s h "
                 "-d 'Display help and exit'\n")
    return "".join(lines)


# ------------------------------------------------------- C embedding

def c_string_fragments(name, text):
    """Emit `static const char NAME[] = ...;` with FUSE_MARK-ed lines
    wrapped in #ifdef BCACHEFS_FUSE - C string concatenation interrupted
    by the preprocessor, which is valid C."""
    out = [f"static const char {name}[] =\n"]
    gated = False
    lines = text.split("\n")
    for i, line in enumerate(lines):
        last = i == len(lines) - 1
        piece = line.replace("\\", "\\\\").replace('"', '\\"')
        tail = "\\n" if not last else ""

        if line.startswith(FUSE_MARK) and not gated:
            out.append("#ifdef BCACHEFS_FUSE\n")
            gated = True
        elif not line.startswith(FUSE_MARK) and gated:
            out.append("#endif\n")
            gated = False

        if line.startswith(FUSE_MARK):
            piece = line[len(FUSE_MARK):]

        out.append(f'\t"{piece}{tail}"\n')
    if gated:
        out.append("#endif\n")
    out.append("\t;\n\n")
    return "".join(out)


def main():
    if len(sys.argv) < 5:
        sys.exit(f"usage: {sys.argv[0]} <bcachefs.c> <cmds.h> <fs/opts.h> "
                 "<commands-dir>")

    bcachefs_c = open(sys.argv[1]).read()
    cmds_h = open(sys.argv[2]).read()
    opts_h = open(sys.argv[3]).read()
    cmd_dir = sys.argv[4]

    warnings = []

    files = {}
    func_index = {}
    for path in sorted(glob.glob(os.path.join(cmd_dir, "*.c"))):
        base = os.path.basename(path)
        if base == "completions.c":
            continue
        text = open(path).read()
        files[base] = text
        for m in re.finditer(r'^\s*(?:static\s+)?int\s+(cmd_\w+)\s*\(',
                             text, re.M):
            func_index[m.group(1)] = base

    opts_table = parse_opts_h(opts_h)
    root = build_tree(bcachefs_c, func_index, files, opts_table, warnings)

    declared = set(re.findall(r'\bint\s+(cmd_\w+)\s*\(', cmds_h))
    declared |= set(re.findall(r'\bint\s+(cmd_\w+)\s*\(', bcachefs_c))
    declared |= set(func_index)
    for c in walk(root):
        if c.handler and c.handler not in declared:
            warnings.append(f"{c.handler}: not declared in cmds.h")

    if not root.children:
        sys.exit("error: no commands parsed from the dispatch table")

    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)

    out = [PROLOG,
           c_string_fragments("COMPLETIONS_BASH", render_bash(root)),
           c_string_fragments("COMPLETIONS_ZSH", render_zsh(root)),
           c_string_fragments("COMPLETIONS_FISH", render_fish(root)),
           EPILOG]
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
